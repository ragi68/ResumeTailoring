/** Zod schemas for every persisted or exchanged shape. Every content item has a stable ID. */
import { z } from 'zod';

export const IdSchema = z.string().min(1).max(120);

/** Dates are stored as YYYY-MM so they render consistently ("Jan 2021"). */
export const YearMonthSchema = z.string().regex(/^\d{4}-(0[1-9]|1[0-2])$/, 'Use YYYY-MM');
export const EndDateSchema = z.union([YearMonthSchema, z.literal('present')]);

export const LinkSchema = z.object({
  label: z.string(),
  url: z.string(),
});

export const HeaderSchema = z.object({
  name: z.string(),
  email: z.string(),
  phone: z.string(),
  location: z.string(),
  links: z.array(LinkSchema),
});

export const BulletSchema = z.object({
  id: IdSchema,
  text: z.string().min(1),
  tags: z.array(z.string()),
  hasMetric: z.boolean(),
  /** User-written alternate phrasings of the same fact. Never generated by the LLM. */
  alternates: z.array(z.string()),
});

export const ExperienceSchema = z.object({
  id: IdSchema,
  company: z.string(),
  title: z.string(),
  location: z.string(),
  start: YearMonthSchema,
  end: EndDateSchema,
  bullets: z.array(BulletSchema),
});

export const ProjectSchema = z.object({
  id: IdSchema,
  name: z.string(),
  links: z.array(LinkSchema),
  bullets: z.array(BulletSchema),
  tags: z.array(z.string()),
});

export const SkillSchema = z.object({
  id: IdSchema,
  name: z.string().min(1),
  aliases: z.array(z.string()),
});

export const SkillGroupSchema = z.object({
  id: IdSchema,
  name: z.string(),
  skills: z.array(SkillSchema),
});

export const EducationSchema = z.object({
  id: IdSchema,
  school: z.string(),
  degree: z.string(),
  location: z.string(),
  start: z.union([YearMonthSchema, z.literal('')]),
  end: EndDateSchema,
  details: z.string(),
});

export const SummaryVariantSchema = z.object({
  id: IdSchema,
  label: z.string(),
  text: z.string(),
  tags: z.array(z.string()),
});

export const MasterResumeSchema = z
  .object({
    version: z.literal(1),
    header: HeaderSchema,
    summaries: z.array(SummaryVariantSchema),
    experience: z.array(ExperienceSchema),
    projects: z.array(ProjectSchema),
    skillGroups: z.array(SkillGroupSchema),
    education: z.array(EducationSchema),
  })
  .superRefine((m, ctx) => {
    const seen = new Set<string>();
    for (const id of allMasterIds(m)) {
      if (seen.has(id)) ctx.addIssue({ code: 'custom', message: `Duplicate id "${id}"` });
      seen.add(id);
    }
  });

export type Link = z.infer<typeof LinkSchema>;
export type Header = z.infer<typeof HeaderSchema>;
export type Bullet = z.infer<typeof BulletSchema>;
export type Experience = z.infer<typeof ExperienceSchema>;
export type Project = z.infer<typeof ProjectSchema>;
export type Skill = z.infer<typeof SkillSchema>;
export type SkillGroup = z.infer<typeof SkillGroupSchema>;
export type Education = z.infer<typeof EducationSchema>;
export type SummaryVariant = z.infer<typeof SummaryVariantSchema>;
export type MasterResume = z.infer<typeof MasterResumeSchema>;

type MasterShape = Pick<MasterResume, 'summaries' | 'experience' | 'projects' | 'skillGroups' | 'education'>;

export function allMasterIds(m: MasterShape): string[] {
  const ids: string[] = [];
  m.summaries.forEach((s) => ids.push(s.id));
  m.experience.forEach((e) => ids.push(e.id, ...e.bullets.map((b) => b.id)));
  m.projects.forEach((p) => ids.push(p.id, ...p.bullets.map((b) => b.id)));
  m.skillGroups.forEach((g) => ids.push(g.id, ...g.skills.map((s) => s.id)));
  m.education.forEach((e) => ids.push(e.id));
  return ids;
}

// ---------------- JD analysis ----------------

export const SENIORITY_LEVELS = [
  'intern',
  'junior',
  'mid',
  'senior',
  'staff',
  'principal',
  'manager',
  'director',
  'executive',
  'unknown',
] as const;

export const JdAnalysisSchema = z.object({
  title: z.string(),
  company: z.string(),
  seniority: z.enum(SENIORITY_LEVELS),
  domain: z.string(),
  requiredSkills: z.array(z.string()),
  niceToHaves: z.array(z.string()),
  keywords: z.array(z.string()),
});
export type JdAnalysis = z.infer<typeof JdAnalysisSchema>;

// ---------------- Selection (per job; never mutates the master) ----------------

export const BlockTypeSchema = z.enum(['experience', 'project', 'education']);
export type BlockType = z.infer<typeof BlockTypeSchema>;

export const BulletRefSchema = z.object({ id: IdSchema, included: z.boolean() });
export type BulletRef = z.infer<typeof BulletRefSchema>;

export const SelectionBlockSchema = z.object({
  type: BlockTypeSchema,
  refId: IdSchema,
  included: z.boolean(),
  /** Ordered bullet ids for this block, each with its own include flag. */
  bullets: z.array(BulletRefSchema),
});
export type SelectionBlock = z.infer<typeof SelectionBlockSchema>;

export const JdSourceSchema = z.enum(['json-ld', 'site', 'selection', 'manual']);

export const JobMetaSchema = z.object({
  title: z.string(),
  company: z.string(),
  url: z.string(),
  jdText: z.string(),
  jdSource: JdSourceSchema,
  analysis: JdAnalysisSchema.nullable(),
  capturedAt: z.number(),
});
export type JobMeta = z.infer<typeof JobMetaSchema>;

export const SelectionSchema = z.object({
  id: IdSchema,
  createdAt: z.number(),
  updatedAt: z.number(),
  job: JobMetaSchema,
  summaryId: IdSchema.nullable(),
  blocks: z.array(SelectionBlockSchema),
  /** Skill ids shown, in order. */
  skillIds: z.array(IdSchema),
  /** Accepted rewrites: bullet id -> replacement text (master text stays untouched). */
  textOverrides: z.record(z.string(), z.string()),
  /** Where the current selection came from, for display. */
  origin: z.enum(['default', 'llm', 'manual']),
  notes: z.array(z.string()),
});
export type Selection = z.infer<typeof SelectionSchema>;

// ---------------- Settings ----------------

export const SectionKeySchema = z.enum(['summary', 'experience', 'projects', 'skills', 'education']);
export type SectionKey = z.infer<typeof SectionKeySchema>;

export const LineBudgetSchema = z.object({
  summary: z.number().int().min(0),
  experience: z.number().int().min(0),
  projects: z.number().int().min(0),
  skills: z.number().int().min(0),
  education: z.number().int().min(0),
});
export type LineBudget = z.infer<typeof LineBudgetSchema>;

export const SettingsSchema = z.object({
  /** Empty means "use the default" (see modelFor). */
  analyzeModel: z.string(),
  tailorModel: z.string(),
  pageLimit: z.union([z.literal(1), z.literal(2)]),
  /** Line budget per section for a one-page resume (a page holds ~53 lines incl. the 3-line header); doubled for two pages. */
  lineBudget: LineBudgetSchema,
  fileNamePattern: z.string(),
  autoFit: z.boolean(),
});
export type Settings = z.infer<typeof SettingsSchema>;

export function modelFor(settings: Settings, step: 'analyze' | 'tailor'): string {
  return step === 'analyze' ? settings.analyzeModel.trim() || DEFAULT_SETTINGS.analyzeModel : settings.tailorModel.trim() || DEFAULT_SETTINGS.tailorModel;
}

export const DEFAULT_SETTINGS: Settings = {
  analyzeModel: 'claude-haiku-5-5',
  tailorModel: 'claude-sonnet-5-5',
  pageLimit: 1,
  lineBudget: { summary: 5, experience: 27, projects: 8, skills: 5, education: 5 },
  fileNamePattern: '{name} Resume - {company}.pdf',
  autoFit: true,
};

export const PinsSchema = z.array(IdSchema);
